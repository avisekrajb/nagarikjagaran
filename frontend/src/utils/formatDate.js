/** AD मितिलाई BS {year,month,day} मा बदल्ने (महिना ०-११) */
export const toBs = (d) => {
  const bs = adToBs(d);
  return bs ? { year: bs.year, month: bs.month, day: bs.day } : null;
};

const totalDays = (y) => (DAYS[y] || []).reduce((a, b) => a + b, 0);

export function adToBs(date) {
  const d = new Date(date);
  if (isNaN(d.getTime())) return null;
  let days = Math.round((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - REF) / 86400000);
  let bsYear = BS_MIN;
  let guard = 0;
  while (bsYear < BS_MAX && days >= totalDays(bsYear) && guard++ < 200) {
    days -= totalDays(bsYear);
    bsYear += 1;
  }
  let bsMonth = 0;
  const mdays = DAYS[bsYear] || [];
  let g2 = 0;
  while (bsMonth < 11 && days >= mdays[bsMonth] && g2++ < 20) {
    days -= mdays[bsMonth];
    bsMonth += 1;
  }
  return { year: bsYear, month: bsMonth, day: days + 1 };
}

const fmt = (d, withWeekday) => {
  const bs = adToBs(d);
  if (!bs) return "";
  const { year, month, day } = bs;
  const base = `${toDev(day)} ${BSM[month]} ${toDev(year)}`;
  return withWeekday ? `${WD[d.getDay()]}, ${base}` : base;
};

export const formatDate = (date = new Date()) => fmt(new Date(date), false);
export const formatDateLong = (date = new Date()) => fmt(new Date(date), true);

export const formatTime = (date = new Date()) => {
  const d = new Date(date);
  return `${pad2(d.getHours())}:${pad2(d.getMinutes())}:${pad2(d.getSeconds())}`;
};

export const nepaliDate = (value = "") => {
  if (!value) return value;
  const d = new Date(String(value).replace(/-/g, "/"));
  if (isNaN(d.getTime())) return String(value);
  return fmt(d, false);
};

export const nepaliDateTime = (value = "") => {
  if (!value) return value;
  const d = new Date(String(value).replace(/-/g, "/"));
  if (isNaN(d.getTime())) return String(value);
  return `${fmt(d, true)}, ${formatTime(d)}`;
};