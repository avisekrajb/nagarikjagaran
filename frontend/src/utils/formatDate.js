/** विक्रम महिनामा कति दिन हुन्छ */
export function bsMonthDays(year, month) {
  const row = DAYS[Number(year)] || [];
  return row[Number(month)] || 30;
}

/** विक्रम सम्वत् -> ई.सं. Date */
export function bsToAd(year, month, day) {
  const y = Number(year);
  const m = Number(month);
  const d = Number(day);

  // तालिका बाहिरको वर्ष/mहिना/दिन मान्य छैन — गलत मिति नदिऔं
  if (!y || Number.isNaN(y) || !DAYS[y]) return null;
  if (Number.isNaN(m) || m < 0 || m > 11) return null;
  if (!d || Number.isNaN(d) || d < 1 || d > (DAYS[y][m] || 0)) return null;

  let days = 0;
  for (let i = BS_MIN; i < y; i += 1) days += totalDays(i);
  const row = DAYS[y];
  for (let i = 0; i < m; i += 1) days += row[i];
  days += d - 1;

  const utc = new Date(REF + days * 86400000);
  if (isNaN(utc.getTime())) return null;
  return new Date(utc.getUTCFullYear(), utc.getUTCMonth(), utc.getUTCDate());
}

/**
 * विक्रम महिनाको पूरा दिन — प्रत्येक दिनको ई.सं. र हप्ताको दिन सहित।
 * weekday: 0 = आइतबार ... 6 = शनिबार
 */
export function bsMonthCells(year, month) {
  const len = bsMonthDays(year, month);
  const start = bsToAd(year, month, 1);
  if (!start) return [];

  const cells = [];
  for (let i = 0; i < len; i += 1) {
    const ad = new Date(start.getFullYear(), start.getMonth(), start.getDate() + i);
    const wd = ad.getDay();
    cells.push({
      bsDay: i + 1,
      ad,
      adDay: ad.getDate(),
      adMonth: ad.getMonth() + 1,
      adYear: ad.getFullYear(),
      weekday: wd,
      weekdayName: WD[wd],
      isSunday: wd === 0,
      isSaturday: wd === 6
    });
  }
  return cells;
}

